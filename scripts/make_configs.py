#!/usr/bin/env python3
"""Materialise configurations from configs/<method>/sensitivity.yaml
(Plan A one-at-a-time sensitivity; brief Section 5.0, step 3).

Every configuration is a self-contained directory configs/<method>/<name>/,
a copy of D with exactly one change, so each run mounts and hashes its full
effective configuration:
  launch_arg    -> written to launch_args.yaml (read by scripts/run_one.py)
  launch_param  -> value="..." of that <param> replaced in launch_file
  key           -> value replaced in yaml_file, path segments separated by '/'
  constant      -> written to constants.env (compile-time; one image per
                   configuration, built by scripts/build_images.py)
A parameter may list several changes that take the same level (e.g. DLO's
joint sub-map keyframe counts). Also writes the configurations without the
sensitivity change that the test phase needs: hdl D_nofloor (Section 5.2).
Writes configs/<method>/configs.yaml with the one-at-a-time names and the
test configurations. Parameters whose status says they still need approval
are skipped. Existing configuration directories are never overwritten.
"""
import argparse
import shutil
import sys
from pathlib import Path

import yaml

R = Path(__file__).resolve().parents[1]
DEFAULT_YAML = {"mesh": "online.yaml", "dlo": "params.yaml"}


def level_values(p):
    return [lv["value"] if isinstance(lv, dict) else lv for lv in p["levels"]]


def fmt(v):
    if isinstance(v, bool):
        return str(v).lower()
    return str(v).replace("-", "m")


def set_nested(doc, path, value):
    keys = path.split("/")
    node = doc
    for k in keys[:-1]:
        node = node[k]
    if keys[-1] not in node:
        raise KeyError(f"{path} not in YAML")
    node[keys[-1]] = value


def apply_change(method, cfg_dir, c, value):
    if "launch_arg" in c:
        f = cfg_dir / "launch_args.yaml"
        args = (yaml.safe_load(f.read_text()) if f.exists() else {}) or {}
        args[c["launch_arg"]] = value
        f.write_text(yaml.safe_dump(args, sort_keys=True))
    elif "launch_param" in c:
        import re
        f = cfg_dir / c["launch_file"]
        text = f.read_text()
        pat = re.compile(r'(<param\s+name="%s"[^>]*?value=")([^"]*)(")' % re.escape(c["launch_param"]))
        new, n = pat.subn(lambda mo: mo.group(1) + str(value) + mo.group(3), text)
        if n != 1:
            raise KeyError(f"<param name={c['launch_param']}> found {n} times in {f}")
        f.write_text(new)
    elif "constant" in c:
        f = cfg_dir / "constants.env"
        lines = f.read_text().splitlines()
        name = c["constant"]
        if not any(l.split("=", 1)[0] == name for l in lines):
            raise KeyError(f"{name} not in {f}")
        lines = [f"{name}={value}" if l.split("=", 1)[0] == name else l for l in lines]
        f.write_text("\n".join(lines) + "\n")
    elif "key" in c:
        f = cfg_dir / c.get("yaml_file", DEFAULT_YAML[method])
        doc = yaml.safe_load(f.read_text())
        set_nested(doc, c["key"], value)
        header = f"# Generated by scripts/make_configs.py from configs/{method}/D: {c['key']} = {value}\n"
        f.write_text(header + yaml.safe_dump(doc, sort_keys=False))
    else:
        raise ValueError(f"change {c} has no launch_arg, launch_param, key or constant")


def apply_param(method, cfg_dir, p, value):
    for c in p.get("changes", [p]):
        apply_change(method, cfg_dir, c, value)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("methods", nargs="+")
    args = ap.parse_args()
    for m in args.methods:
        base = R / "configs" / m
        design = yaml.safe_load((base / "sensitivity.yaml").read_text())
        if design.get("status") != "LOCKED":
            raise SystemExit(f"{m}: sensitivity design not locked")
        names = []
        for p in design["parameters"]:
            for v in p["levels"]:
                name = f"OAT_{p['id']}_{fmt(v)}"
                d = base / name
                if not d.exists():
                    shutil.copytree(base / "D", d, ignore=shutil.ignore_patterns("README.md"))
                    apply_param(m, d, p, v)
                    (d / "CHANGE.txt").write_text(
                        f"One-at-a-time configuration: D with {p['id']} ({p['name']}) = {v} {p['unit']} "
                        f"(default {p['default']}); generated by scripts/make_configs.py\n")
                names.append(name)
        test = ["D"]
        if m == "hdl":
            d = base / "D_nofloor"
            if not d.exists():
                shutil.copytree(base / "D", d, ignore=shutil.ignore_patterns("README.md"))
                apply_change(m, d, {"launch_arg": "enable_floor_detection"}, False)
                (d / "CHANGE.txt").write_text("Floor-constraint ablation (brief Section 5.2): D with "
                                              "enable_floor_detection = false\n")
            test.append("D_nofloor")
        (base / "configs.yaml").write_text(yaml.safe_dump({"oat": names, "test": test}, sort_keys=False))
        print(f"{m}: {len(names)} one-at-a-time configurations; test: {test}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
