#!/usr/bin/env python3
"""Dataset inventory (brief Section 4.3): rosbag-info-like summary of every bag
of every sequence, plus LiDAR scan rate and points per scan, written to
datasets/inventory.md and datasets/inventory.json. Bags that are not present
are listed as missing."""
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import yaml

R = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(R / "eval"))
from slameval import bagio  # noqa: E402


def data_root(seqs=None):
    """Bag root: $SLAMBENCH_DATA if set, else data_root in datasets/sequences.yaml,
    else datasets/."""
    import os
    import yaml
    if os.environ.get("SLAMBENCH_DATA"):
        return Path(os.environ["SLAMBENCH_DATA"]).resolve()
    seqs = seqs or yaml.safe_load((R / "datasets" / "sequences.yaml").read_text())
    root = str(seqs.get("data_root") or "")
    return Path(root).resolve() if root and "$" not in root else (R / "datasets").resolve()

def lidar_scan_stats(bags, topic, n=100):
    """Header-stamp rate and points per scan from the first n LiDAR messages."""
    from rosbags.highlevel import AnyReader
    stamps, pts, info = [], [], {}
    with AnyReader([Path(b) for b in bags], default_typestore=bagio.TYPESTORE) as r:
        conns = [c for c in r.connections if c.topic == topic]
        for c, _, raw in r.messages(connections=conns):
            m = r.deserialize(raw, c.msgtype)
            stamps.append(m.header.stamp.sec + m.header.stamp.nanosec * 1e-9)
            pts.append(m.width * m.height)
            if not info:
                info = {"frame_id": m.header.frame_id, "fields": [f.name for f in m.fields],
                        "point_step": m.point_step, "height": m.height}
            if len(stamps) >= n:
                break
    dt = np.diff(stamps)
    return {**info, "n_sampled": len(stamps), "first_header_stamp": stamps[0] if stamps else None,
            "median_period_s": float(np.median(dt)) if len(dt) else None,
            "points_per_scan_median": float(np.median(pts)) if pts else None,
            "points_per_scan_min": int(min(pts)) if pts else None,
            "points_per_scan_max": int(max(pts)) if pts else None}


def fmt_t(t):
    return datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%d %H:%M:%S") if t else "-"


def main():
    seqs = yaml.safe_load((R / "datasets" / "sequences.yaml").read_text())["sequences"]
    root = data_root()
    inv = {}
    md = ["# Dataset inventory", "",
          f"Generated by `scripts/inventory.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC. "
          f"Bag root: `{root}`. Times are recording times in UTC.", ""]
    for seq, cfg in seqs.items():
        bags = [root / b for b in cfg["bags"]]
        missing = [str(b) for b in bags if not b.exists()]
        md += [f"## {seq} ({cfg['dataset']}, {cfg.get('folder', '')}, role: {cfg['role']})", ""]
        if missing:
            inv[seq] = {"missing": missing}
            md += ["Missing bags: " + ", ".join(f"`{Path(m).name}`" for m in missing), ""]
            continue
        per_bag = {b.name: bagio.topic_summary([b]) for b in bags}
        total = bagio.topic_summary(bags)
        lidar = lidar_scan_stats(bags, cfg["lidar_topic"])
        inv[seq] = {"bags": per_bag, "combined": total, "lidar": lidar}
        tb = total["_bag"]
        # Same clock check: LiDAR header stamps must fall inside the ground-truth
        # span (the 18 July CitrusFarm recordings overlap in time, so their clock
        # is not wall time; what matters is that LiDAR and ground truth agree).
        gq = R / "gt" / seq / "gt_quality.json"
        if gq.exists() and lidar.get("first_header_stamp"):
            g = json.loads(gq.read_text())
            lidar_end = total[cfg["lidar_topic"]]["end"]
            inv[seq]["clock_check"] = {
                "lidar_first_stamp_minus_gt_start_s": lidar["first_header_stamp"] - g["t_start"],
                "lidar_last_record_minus_gt_end_s": lidar_end - g["t_end"]}
            md.append(f"Clock check: first LiDAR header stamp is "
                      f"{inv[seq]['clock_check']['lidar_first_stamp_minus_gt_start_s']:+.2f} s from the "
                      f"ground-truth start; last LiDAR message "
                      f"{inv[seq]['clock_check']['lidar_last_record_minus_gt_end_s']:+.2f} s from its end.")
            md.append("")
        md += [f"Duration {tb['duration_s']:.1f} s ({tb['duration_s'] / 60:.2f} min), "
               f"{fmt_t(tb['start'])} to {fmt_t(tb['end'])}, {tb['message_count']} messages "
               f"in {len(bags)} bag(s).", "",
               f"LiDAR `{cfg['lidar_topic']}`: frame `{lidar.get('frame_id')}`, median header period "
               f"{lidar.get('median_period_s')} s, points per scan median {lidar.get('points_per_scan_median')} "
               f"(min {lidar.get('points_per_scan_min')}, max {lidar.get('points_per_scan_max')}), "
               f"fields {lidar.get('fields')}.", "",
               "| Topic | Type | Count | Median rate (Hz) | Start | End |", "|---|---|---|---|---|---|"]
        for topic, v in total.items():
            if topic == "_bag":
                continue
            rate = f"{v['median_rate_hz']:.2f}" if v["median_rate_hz"] else "-"
            md.append(f"| `{topic}` | `{v['type']}` | {v['count']} | {rate} | {fmt_t(v['start'])} | {fmt_t(v['end'])} |")
        md += ["", "Per bag:", ""]
        for name, s in per_bag.items():
            b = s["_bag"]
            md.append(f"- `{name}`: {b['duration_s']:.1f} s, {fmt_t(b['start'])} to {fmt_t(b['end'])}, "
                      f"{b['message_count']} messages")
        md.append("")
    (R / "datasets" / "inventory.json").write_text(json.dumps(inv, indent=1, default=str) + "\n")
    (R / "datasets" / "inventory.md").write_text("\n".join(md) + "\n")
    print("wrote datasets/inventory.md")


if __name__ == "__main__":
    main()
