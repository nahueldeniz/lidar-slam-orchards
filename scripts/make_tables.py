def t5_resources(ctx):
    if ctx.table("resources_summary") is None:
        return "skipped: no resources_summary.csv"
    rows, topics = [], []
    for m in METHODS:
        ratio = ctx.realtime_column(m, "processed_scan_ratio")
        lat_med = ctx.realtime_column(m, "latency_median_s")
        lat_p95 = ctx.realtime_column(m, "latency_p95_s")
        topics.append(f"{LABEL[m]} {ratio.rsplit(':', 1)[0] if ratio else 'N/A'}")
        for s in ctx.test_seqs():
            n_ok, n = ctx.run_count(m, s, "D")
            r = lambda col, sc=1.0: ctx.resource(m, s, "D", col, scale=sc)  # noqa: E731
            rows.append({
                "Method": LABEL[m], "Sequence": ctx.seq_label(s), "Runs": f"{n_ok}/{n}",
                "CPU mean (% of one core)": r("cpu_mean_pct_one_core").text(counts=False, d=0),
                "CPU p95 (%)": r("cpu_p95_pct_one_core").text(counts=False, d=0),
                "RSS peak (GB)": r("rss_peak_gb").text(counts=False, d=2),
                "USS peak (GB)": r("uss_peak_gb").text(counts=False, d=2),
                "Power mean (W)": r("power_mean_w").text(counts=False, d=1),
                "Incremental power (W)": r("power_incremental_w").text(counts=False, d=1),
                "Energy (Wh)": r("energy_wh").text(counts=False, d=2),
                "Processed scans (%)": r(ratio, 100.0).text(counts=False, d=1),
                "Latency median (ms)": r(lat_med, 1000.0).text(counts=False, d=1),
                "Latency p95 (ms)": r(lat_p95, 1000.0).text(counts=False, d=1),
            })
    notes = ["Configuration D; mean ± SD over successful repetitions (Runs: successful/attempted). CPU: 100 % = "
             "one logical core, method processes only (container cgroup and psutil). RSS and USS: peak over the "
             "run. Power: CPU package (RAPL) over the playback window; incremental = minus the infrastructure-only "
             "baseline of the same sequence. Processed scans: output stamps matching input scans / input scans. "
             "Latency: output receipt minus input receipt. Real-time topics: " + "; ".join(topics) + ". "
             "2D and 3D errors come from the same runs, so their resource figures are identical."]
    missing = sorted(n for n in ctx.notes if n.endswith(tuple(f"D rep{k}" for k in range(1, 10))))
    if missing:
        notes.append("Not available in otherwise successful runs: " + "; ".join(missing[:20]) +
                     (" ..." if len(missing) > 20 else "") + ".")
    return write(pd.DataFrame(rows), "T5_resources", "Resource use and real-time behaviour", notes, resize=True)


