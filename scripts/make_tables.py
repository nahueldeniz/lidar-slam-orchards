        ("Core types", ", ".join(f"{k}: CPUs {v}" for k, v in hybrid.items()) or "N/A"),
        ("Memory", f"{m['memory']['mem_total_kb'] / 1024 ** 2:.1f} GiB RAM, "
                   f"{m['memory']['swap_total_kb'] / 1024 ** 2:.1f} GiB swap"),
        ("Storage", ", ".join(f"{d['model'].strip()} ({d['size_gb']:.0f} GB)" for d in m["storage"]["disks"])),
