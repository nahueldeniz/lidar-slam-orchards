#!/usr/bin/env python3
"""Tables T1-T7 (brief Section 14) as CSV and LaTeX (booktabs) into tables/.

Every cell comes from a pipeline output; a value that is not available yet is
written as 'N/A' with the reason in the table notes, never filled by hand. A
table whose inputs do not exist yet is skipped with a message.

Aggregation (brief Section 12): mean ± SD (sample SD) over repetitions per
method x sequence x configuration x output, never across sequences. Runs that
failed are counted in the 'Runs' column (successful/attempted) and reported
as 'failed', never dropped silently.

  T1  ground-truth characteristics per sequence      gt/<seq>/gt_quality.json, datasets/sequences.yaml
  T2  software versions                              env/src_pins_*.json, env/images.json
  T3  sensitivity parameters and measured ΔRMSE      configs/<m>/sensitivity.yaml, configs/SENSITIVITY_DESIGN.md,
                                                     eval/results_long.csv (+ T3_sensitivity_long.csv)
  T4  accuracy, alignment A (main) and B (suppl.)    eval/results_long.csv, eval/run_diagnostics.csv
                                                     (+ T4_accuracy_all.csv: every aggregate, CSV only)
  T5  resources and real-time behaviour              eval/resources_summary.csv
  T6  hdl floor-constraint ablation                  eval/results_long.csv
  T7  machine specification                          env/machine.json

Usage: make_tables.py [T4 ...] [--results-dir eval] [--gt-dir gt] [--configs-dir configs]
       [--env-dir env] [--out-dir tables]
"""
