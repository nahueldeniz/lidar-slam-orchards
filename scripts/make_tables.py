_TEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "$": r"\$",
        "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
        "±": r"$\pm$", "Δ": r"$\Delta$", "σ": r"$\sigma$", "≥": r"$\geq$", "≤": r"$\leq$",
        "×": r"$\times$", "²": r"$^{2}$", "°": r"\textdegree{}", "−": r"$-$", "†": r"\textdagger{}",
        "µ": r"$\mu$", "→": r"$\rightarrow$", "/": r"/\allowbreak{}"}


def latex_escape(s):
    return "".join(_TEX.get(ch, ch) for ch in str(s))


def _P(cm):
    """Ragged-right paragraph column of the given width (needs the array package)."""
    return rf">{{\raggedright\arraybackslash}}p{{{cm}cm}}"


def write(df, name, caption, notes=(), resize=False, colspec=None):
    """CSV plus LaTeX booktabs table. colspec: LaTeX column types (default all 'l');
    resize: scale the tabular to the text width."""
    OUT.mkdir(parents=True, exist_ok=True)
    df = df.fillna("N/A")
    df.to_csv(OUT / f"{name}.csv", index=False)
    cols = colspec or "l" * len(df.columns)
    lines = [r"% Generated by scripts/make_tables.py; needs \usepackage{booktabs,array,graphicx}.",
             r"\begin{table}[htbp]", r"\centering", rf"\caption{{{latex_escape(caption)}}}",
             rf"\label{{tab:{name}}}", r"\small"]
    if resize:
        lines.append(r"\resizebox{\textwidth}{!}{%")
    lines += [rf"\begin{{tabular}}{{{cols}}}", r"\toprule",
              " & ".join(latex_escape(c) for c in df.columns) + r" \\", r"\midrule"]
    for _, row in df.iterrows():
        lines.append(" & ".join(latex_escape(v) for v in row.values) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}" + ("}" if resize else "")]
    if notes:
        lines.append(r"\par\smallskip\footnotesize " + " ".join(latex_escape(n) for n in notes))
    lines.append(r"\end{table}")
    (OUT / f"{name}.tex").write_text("\n".join(lines) + "\n")
    return "ok"


def runs_text(a: Agg):
    return f"{a.n_ok}/{a.n_total}" if a.n_total else "0"


# ---------------------------------------------------------------- T1
def t1_ground_truth(ctx):
    rows, notes = [], set()
    for s, cfg in ctx.seqs.items():
        q = ctx.quality(s)
        if q is None or not cfg.get("enabled", True):
            continue
        rtk = q.get("rtk", {})
        fixed = sig_h = sig_v = "N/A"
        if rtk.get("status") == "ok":
            modes = (rtk.get("receiver_state") or {}).get("fix_mode_counts")
            if modes:   # receiver's own solution type (piksi receiver_state)
                fixed = f"{100.0 * modes.get('FIXED_RTK', 0) / sum(modes.values()):.1f}"
            else:       # NavSatFix status only (Pullally: status 2 = GBAS fix)
                fixed = f"{rtk['fix_status_percent'].get('GBAS fix', 0.0):.1f} (status 2)"
            sig = rtk["sigma_enu_m"]
            sig_h = f"{max(sig['E']['median'], sig['N']['median']):.3f}"
            sig_v = f"{sig['U']['median']:.3f}"
        else:
            notes.add("N/A: needs the base bags (raw RTK topics).")
        la = cfg.get("lever_arm_lidar_to_antenna_m")
        rows.append({
            "Sequence": s, "Role": cfg["role"],
            "Receiver": RECEIVER[cfg["dataset"]]["receiver"],
            "Base station": RECEIVER[cfg["dataset"]]["base_station"],
            "Rate (Hz)": f"{q['median_rate_hz']:.1f}",
            "Gaps > 2 periods": len(q["gaps"]),
            "Fixed (%)": fixed, "sigma_H (m)": sig_h, "sigma_V (m)": sig_v,
            "Lever arm LiDAR to antenna (m)": "N/A" if la is None else f"({la[0]:.3f}, {la[1]:.3f}, {la[2]:.3f})",
        })
    if not rows:
        return "skipped: no gt/<seq>/gt_quality.json"
    notes.add("CitrusFarm ground truth: post-processed positions (gt.bag /gps/fix/odometry), "
              "no orientation, no covariance.")
    return write(pd.DataFrame(rows), "T1_ground_truth", "Ground-truth characteristics per sequence",
                 sorted(notes), resize=True)


# ---------------------------------------------------------------- T2
_ID_KEYS = ("url", "repository", "sha", "head_sha", "tag", "apt_version", "version", "package", "apt_package")
_SKIP = ("_comment", "build", "open_questions", "official_image_reference_only", "history_notes",
         "local_clone_state", "other_remote_branches_not_used")


def _short(sha):
    return str(sha)[:12] if sha else ""


def _component(name, e):
    src = e.get("url") or e.get("repository") or ""
    if not src and (e.get("apt_package") or e.get("package")):
        src = f"apt {e.get('apt_package') or e.get('package')}"
    src = src or e.get("upstream") or e.get("source") or ""
    version = e.get("tag") or e.get("version_stated") or ""
    chosen = str(e.get("chosen_for_docker") or "").split(" ")[0]
    version = version or chosen or e.get("apt_version") or e.get("version") or ""
    if not version and e.get("branch"):
        version = f"branch {e['branch']}"
    sha = e.get("sha") or e.get("head_sha") or e.get("tag_commit_sha") or ""
    if not sha and chosen and isinstance(e.get("candidate_tags"), dict):
        sha = (e["candidate_tags"].get(chosen) or {}).get("tag_commit_sha", "")
    if not sha and e.get("sha256"):
        sha = "sha256 " + _short(e["sha256"])
    date = e.get("commit_date") or e.get("head_commit_date") or e.get("tag_commit_date") or ""
    patches = "; ".join(Path(str(p).split(" ")[0]).name + (" " + " ".join(str(p).split(" ")[1:]) if " " in str(p) else "")
                        for p in e.get("patches", []) or [])
    return {"Component": name, "Source": src, "Version": str(version), "Commit": _short(sha) if not
            str(sha).startswith("sha256") else sha, "Commit date": str(date)[:10], "Patches": patches or "none"}


def _components(method, d):
    """Rows for one method entry of an src_pins file (two layouts are in use)."""
    rows = []
    if any(k in d for k in ("repository", "url")):          # the method entry is the repository itself
        rows.append(_component(Path(str(d.get("repository") or d.get("url"))).name, d))
        dep = d.get("dependency_required_by_readme")
        if isinstance(dep, dict):
            rows.append(_component(dep.get("name", "dependency"), dep))
    for k, v in d.items():
        if k in _SKIP or k.startswith("_") or not isinstance(v, dict) or k == "dependency_required_by_readme":
            continue
        if any(x in v for x in _ID_KEYS):
            rows.append(_component(k, v))
        elif k == "apt_pins":
            rows += [{"Component": p, "Source": f"apt {p}", "Version": ver, "Commit": "", "Commit date": "",
                      "Patches": "none"} for p, ver in v.items() if p != "note"]
        else:                                                # one more level (e.g. fetched dependencies)
            for k2, v2 in v.items():
                if isinstance(v2, dict) and any(x in v2 for x in _ID_KEYS):
                    rows.append(_component(k2, v2))
    out, seen = [], set()
    for r in rows:     # the same apt package can be listed twice (component and apt_pins)
        key = (r["Source"], r["Version"])
        if key in seen:
            continue
        seen.add(key)
        r["Method"] = LABEL.get(method, method)
        out.append(r)
    return out


def t2_software(ctx):
    pins = sorted(ctx.env_dir.glob("src_pins_*.json"))
    img_file = ctx.env_dir / "images.json"
    if not pins and not img_file.exists():
        return "skipped: no env/src_pins_*.json or env/images.json"
    entries = {}
    for f in pins:
        for k, v in json.loads(f.read_text()).items():
            if k in METHODS and isinstance(v, dict):
                entries[k] = v
    images = json.loads(img_file.read_text()) if img_file.exists() else {}
    rows, notes = [], []
    for m in METHODS:
        rows += _components(m, entries.get(m, {})) if m in entries else [
            {"Method": LABEL[m], "Component": "N/A", "Source": "no src_pins entry", "Version": "", "Commit": "",
             "Commit date": "", "Patches": ""}]
        mine = {k: v for k, v in images.items() if (v.get("labels") or {}).get("slambench.method") == m}
        if mine:
            main = next((k for k in mine if k.endswith(":D")), None) or next(iter(mine))
            ok = sum(1 for v in mine.values() if v.get("returncode") == 0)
            rows.append({"Method": LABEL[m], "Component": "Docker image", "Source": main,
                         "Version": f"{len(mine)} image(s), {ok} built" if len(mine) > 1 else "1 image",
                         "Commit": "image ID " + str(mine[main].get("id", "")).replace("sha256:", "")[:12],
                         "Commit date": "", "Patches": ""})
        else:
            rows.append({"Method": LABEL[m], "Component": "Docker image", "Source": "N/A", "Version": "",
                         "Commit": "", "Commit date": "", "Patches": ""})
    notes.append("Commit: first 12 hexadecimal digits of the git commit; image ID: first 12 digits of the local "
                 "Docker image ID (env/images.json). Methods with compile-time parameters (LeGO-LOAM, A-LOAM) "
                 "have one image per configuration; the configuration D image is listed.")
    cols = ["Method", "Component", "Source", "Version", "Commit", "Commit date", "Patches"]
    df = pd.DataFrame(rows)[cols].rename(columns={"Commit": "Commit or image ID"})
    return write(df, "T2_software", "Software versions", notes, resize=True,
                 colspec="ll" + _P(6.5) + _P(3.8) + "ll" + _P(6.5))


# ---------------------------------------------------------------- T3
def _key(p):
    """Parameter key(s); several keys under one path are written as prefix/{a, b, c}."""
    keys = []
    for c in p.get("changes", []) or []:
        k = c.get("launch_arg") or c.get("constant") or c.get("launch_param") or c.get("key")
        if k:
            keys.append(str(k))
    if len(keys) > 1:
        heads = {k.rpartition("/")[0] for k in keys}
        if len(heads) == 1 and heads != {""}:
            return f"{heads.pop()}/{{{', '.join(k.rpartition('/')[2] for k in keys)}}}"
    return ", ".join(keys) or "N/A"


def t3_parameters(ctx):
    if not ctx.designs:
        return "skipped: no configs/<method>/sensitivity.yaml"
    rows, long_rows, notes = [], [], []
    have_results = ctx.table("results_long") is not None
    have_res = ctx.table("resources_summary") is not None
    for m in METHODS:
        d = ctx.designs.get(m)
        if not d:
            continue
        seq = d.get("sequence", "cf_5")
        hl = ctx.headline(m)
        ref = ctx.accuracy(m, seq, "D", hl)
        rt_col = ctx.realtime_column(m) if have_res else None
        refs = {"rmse": ref, "cpu": ctx.resource(m, seq, "D", "cpu_mean_pct_one_core"),
                "rss": ctx.resource(m, seq, "D", "rss_peak_gb")}
        if rt_col:
            refs["processed"] = ctx.resource(m, seq, "D", rt_col)
        reasons = ctx.design_reasons.get(m, [])
        if reasons and len(reasons) != len(d["parameters"]):
            notes.append(f"{m}: SENSITIVITY_DESIGN.md lists {len(reasons)} parameters, sensitivity.yaml "
                         f"{len(d['parameters'])}; reasons not matched.")
            reasons = []
        for i, p in enumerate(d["parameters"]):
            row = {"Method": LABEL[m], "ID": p["id"], "Parameter": report.param_name(p), "Key": _key(p),
                   "Unit": str(p.get("unit", "")).replace("^2", "²"), "Module": p.get("module", ""),
                   "Default (D)": str(p["default"]), "Levels": ", ".join(str(v) for v in p["levels"])}
            for k, v in enumerate(p["levels"], 1):
                cname = report.oat_name(p["id"], v)
                vals = {"rmse": ctx.accuracy(m, seq, cname, hl),
                        "cpu": ctx.resource(m, seq, cname, "cpu_mean_pct_one_core"),
                        "rss": ctx.resource(m, seq, cname, "rss_peak_gb")}
                if rt_col:
                    vals["processed"] = ctx.resource(m, seq, cname, rt_col)
                a, r = vals["rmse"], refs["rmse"]
                if not have_results:
                    txt = "N/A"
                elif a.n_ok and r.n_ok:
                    dv = a.mean - r.mean
                    txt = fmt(dv, sign=True, d=report.decimals(r.mean)) + \
                        (" *" if r.n_ok > 1 and abs(dv) <= r.sd else "")
                    pr = vals.get("processed")
                    if pr is not None and pr.n_ok and pr.mean < 0.95:
                        txt += f" † ({100 * pr.mean:.0f} % processed)"
                else:
                    txt = "failed" if a.status == "failed" else "N/A" if r.n_ok else "N/A (no D)"
                row[f"ΔRMSE level {k} (m)"] = txt
                lr = {"method": m, "seq": seq, "param_id": p["id"], "parameter": report.param_name(p), "level": v,
                      "config": cname, "output": hl}
                for q, a in vals.items():
                    r = refs[q]
                    lr.update({f"{q}_n_ok": a.n_ok, f"{q}_n_total": a.n_total, f"{q}_value": a.mean,
                               f"{q}_D_mean": r.mean, f"{q}_D_sd": r.sd, f"{q}_D_n": r.n_ok,
                               f"delta_{q}": a.mean - r.mean if a.n_ok and r.n_ok else np.nan})
                long_rows.append(lr)
            row["Reason"] = reasons[i]["reason"] if reasons else "N/A"
            rows.append(row)
        if have_results:
            notes.append(f"{LABEL[m]}: D on {seq} {ref.text()} m RMSE (n = {ref.n_ok}).")
    notes = [f"ΔRMSE: RMSE of the configuration with one parameter at the given level minus the mean RMSE of the "
             f"D runs on the sensitivity sequence (headline output, alignment A, 3D error, main lever-arm "
             f"setting); one run per level. * = within ± 1 SD of the D runs (run-to-run spread). Plan A: no tuned "
             f"configuration T; the submitted P1–P3 values are listed in the brief (Sections 5.1–5.7). "
             f"† = fewer than 95 % of the scans processed: the method fell behind real time, so its RMSE covers "
             f"only part of the run and is not comparable with D."] + notes
    if not have_results:
        notes.append("ΔRMSE N/A: no results_long.csv yet.")
    if long_rows and (have_results or have_res):
        OUT.mkdir(parents=True, exist_ok=True)
        pd.DataFrame(long_rows).to_csv(OUT / "T3_sensitivity_long.csv", index=False)
    return write(pd.DataFrame(rows), "T3_parameters", "Parameters varied in the one-at-a-time sensitivity "
                 "analysis and their measured effect", notes, resize=True,
                 colspec="ll" + _P(3.6) + _P(5.2) + "l" + _P(2.2) + "llll" + _P(5.5))


# ---------------------------------------------------------------- T4
def _flag_text(f):
    parts = []
    if f["coverage"]:
        parts.append(f"coverage < 95 % ({f['coverage']})")
    if f["diverged"]:
        parts.append(f"divergence flagged ({f['diverged']})")
    if f["no_output"]:
        parts.append(f"no output ({f['no_output']})")
    if f["run_failed"]:
        parts.append(f"run failed ({f['run_failed']})")
    return "; ".join(parts) or "none"


def _aggregate_all(ctx):
    """Every aggregate of results_long.csv (all configurations, outputs, alignments,
    lever-arm settings, dimensions and metrics): mean, SD, n over repetitions."""
    df = ctx.table("results_long")
    keys = ["method", "seq", "config", "output", "alignment", "lever_arm", "dim", "metric"]
    g = df.groupby(keys, sort=False)["value"]
    out = g.agg(n_ok="count", mean="mean", sd="std", min="min", max="max").reset_index()
    out["n_attempted"] = [len(ctx._attempts.get(tuple(r[:4]), set()) | set())
                          for r in out[["method", "seq", "config", "output"]].itertuples(index=False)]
    out["n_attempted"] = out[["n_attempted", "n_ok"]].max(axis=1)
    return out


def t4_accuracy(ctx):
    if ctx.table("results_long") is None:
        return "skipped: no results_long.csv"
    OUT.mkdir(parents=True, exist_ok=True)
    _aggregate_all(ctx).to_csv(OUT / "T4_accuracy_all.csv", index=False)
    seqs = ctx.test_seqs()
    for alignment, name, title in (("A", "T4_accuracy", "global alignment A (main)"),
                                   ("B", "T4_accuracy_B", "initial-segment alignment B (supplementary)")):
        rows = []
        for m in METHODS:
            for o in ctx.outputs(m):
                for s in seqs:
                    acc = {k: ctx.accuracy(m, s, "D", o, metric=k, alignment=alignment)
                           for k in ("rmse", "mean", "median", "max", "final", "rmse_pct")}
                    rm = acc["rmse"]
                    rows.append({
                        "Method": LABEL[m], "Output": ctx.output_label(m, o), "Sequence": ctx.seq_label(s),
                        "Lever arm": rm.lever or ctx.lever(s), "Runs": runs_text(rm),
                        "RMSE (m)": rm.text(counts=False),
                        "Mean (m)": acc["mean"].text(sd=False, counts=False),
                        "Median (m)": acc["median"].text(sd=False, counts=False),
                        "Max (m)": acc["max"].text(sd=False, counts=False),
                        "Final (m)": acc["final"].text(sd=False, counts=False),
                        "RMSE (% of path)": acc["rmse_pct"].text(sd=False, counts=False, d=2),
                        "Flags": _flag_text(ctx.flags(m, s, "D", o)),
                    })
        notes = [f"Configuration D, 3D position error after {title}. RMSE: mean ± SD over repetitions; mean, "
                 "median, max and final error: mean over repetitions. Runs: repetitions with a value / repetitions "
                 "attempted; failed runs are not averaged. Lever arm: main setting per dataset "
                 "(eval/config/outputs.yaml); 'without' where the lever arm is unknown. Every other aggregate "
                 "(2D, vertical, other configurations and lever-arm settings) is in T4_accuracy_all.csv."]
        write(pd.DataFrame(rows), name, f"Position accuracy, {title}", notes, resize=True)
    return "ok"


